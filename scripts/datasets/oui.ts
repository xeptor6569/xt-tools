// Dataset: IEEE Registration Authority MAC assignment lists (public registry
// data). Used by src/tools/mac-vendor. The site loads the generated JSON
// through loadLocalAsset and never requests these URLs.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Dataset } from '../refresh-data.ts';
import { ROOT } from '../lib/tools.ts';

const CONSTANT_FILE = join(ROOT, 'src', 'tools', 'mac-vendor', 'dataset.ts');
const FILE = 'oui-2026-10.json';

const SOURCES = [
  { url: 'https://standards-oui.ieee.org/oui/oui.csv', registry: 'MA-L' },
  { url: 'https://standards-oui.ieee.org/oui28/mam.csv', registry: 'MA-M' },
  { url: 'https://standards-oui.ieee.org/oui36/oui36.csv', registry: 'MA-S' },
] as const;

export interface OuiRow {
  prefix: string;
  name: string;
  registry: string;
}

/** Parse one IEEE assignment CSV into prefix rows. */
export function parseOuiCsv(text: string, registry: string): OuiRow[] {
  const rows = parseCsv(text.charCodeAt(0) === 0xfeff ? text.slice(1) : text);
  const header = rows[0];
  if (!header) throw new Error('The OUI CSV has no header.');
  const assignment = header.indexOf('Assignment');
  const name = header.indexOf('Organization Name');
  if (assignment < 0 || name < 0) throw new Error('The OUI CSV is missing Assignment or Organization Name.');
  const out: OuiRow[] = [];
  for (const row of rows.slice(1)) {
    if (row.every((cell) => cell.trim() === '')) continue;
    const prefix = (row[assignment] ?? '').trim().toUpperCase();
    const vendor = (row[name] ?? '').replace(/\s+/g, ' ').trim();
    if (!/^[0-9A-F]{6,}$/.test(prefix)) throw new Error(`Bad OUI assignment "${prefix}" in ${registry}.`);
    if (vendor === '') throw new Error(`OUI ${prefix} has no organization name.`);
    out.push({ prefix, name: vendor, registry });
  }
  return out;
}

/** Merge rows. A repeated prefix keeps each distinct name in file order. */
export function ouiTable(rows: readonly OuiRow[]): Record<string, string> {
  const names = new Map<string, string[]>();
  for (const row of rows) {
    const list = names.get(row.prefix) ?? [];
    if (!list.includes(row.name)) list.push(row.name);
    names.set(row.prefix, list);
  }
  const table: Record<string, string> = {};
  for (const prefix of [...names.keys()].sort()) table[prefix] = (names.get(prefix) ?? []).join(' / ');
  return table;
}

function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const char = text[i] ?? '';
    if (quoted) {
      if (char === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 1;
        } else quoted = false;
      } else field += char;
      continue;
    }
    if (char === '"') quoted = true;
    else if (char === ',') {
      row.push(field);
      field = '';
    } else if (char === '\n') {
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else if (char !== '\r') field += char;
  }
  if (field.length > 0 || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

async function getText(url: string): Promise<string> {
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(url, { headers: { 'User-Agent': 'xt-tools-refresh-data' } });
    if (res.ok) return await res.text();
    if (attempt >= 3) throw new Error(`GET ${url}: HTTP ${res.status}`);
    await new Promise((resolve) => setTimeout(resolve, 500 * attempt));
  }
}

export async function refresh(): Promise<Dataset> {
  const rows: OuiRow[] = [];
  const counts: Record<string, number> = {};
  for (const source of SOURCES) {
    console.log(`  downloading ${source.registry} from ${source.url}`);
    const parsed = parseOuiCsv(await getText(source.url), source.registry);
    counts[source.registry] = parsed.length;
    rows.push(...parsed);
  }
  const table = ouiTable(rows);
  const prefixes = Object.keys(table).length;
  writeFileSync(
    CONSTANT_FILE,
    `// Generated by \`node scripts/refresh-data.ts oui\`. Do not edit by hand.\nexport const DATA_FILE = 'data/${FILE}';\n`,
  );
  console.log(`  ~ src/tools/mac-vendor/dataset.ts -> data/${FILE} (${prefixes} prefixes)`);
  const notes = [
    `${prefixes} prefixes: MA-L ${counts['MA-L'] ?? 0}, MA-M ${counts['MA-M'] ?? 0}, MA-S ${counts['MA-S'] ?? 0}.`,
    'Lookup uses the longest matching prefix, so a 28-bit or 36-bit assignment wins over the 24-bit block it was carved from.',
  ].join(' ');
  return {
    name: 'oui',
    file: FILE,
    content: JSON.stringify(table),
    source: 'IEEE Registration Authority',
    url: SOURCES[0].url,
    version: '2026-10',
    license: 'IEEE public registry data',
    tool: 'mac-vendor',
    notes,
  };
}
