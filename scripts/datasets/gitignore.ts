// Dataset: .gitignore templates from github/gitignore (CC0-1.0), pinned to the
// current `main` commit. Used by src/tools/gitignore-generator.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Dataset } from '../refresh-data.ts';
import { ROOT } from '../lib/tools.ts';

const REPO = 'github/gitignore';
const API = `https://api.github.com/repos/${REPO}`;
const RAW = `https://raw.githubusercontent.com/${REPO}`;
const CONSTANT_FILE = join(ROOT, 'src', 'tools', 'gitignore-generator', 'dataset.ts');

interface Template {
  name: string;
  group: string;
  path: string;
  content: string;
}

interface TreeEntry {
  path: string;
  type: string;
}

function headers(): Record<string, string> {
  const h: Record<string, string> = { Accept: 'application/vnd.github+json', 'User-Agent': 'xt-tools-refresh-data' };
  const token = process.env.GITHUB_TOKEN;
  if (token) h.Authorization = `Bearer ${token}`;
  return h;
}

async function getJson<T>(url: string): Promise<T> {
  const res = await fetch(url, { headers: headers() });
  if (!res.ok) throw new Error(`GET ${url}: HTTP ${res.status}`);
  return (await res.json()) as T;
}

async function getText(url: string): Promise<string> {
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(url, { headers: { 'User-Agent': 'xt-tools-refresh-data' } });
    if (res.ok) return await res.text();
    if (attempt >= 3) throw new Error(`GET ${url}: HTTP ${res.status}`);
    await new Promise((r) => setTimeout(r, 500 * attempt));
  }
}

/** Which group a path belongs to, or undefined to skip it. */
export function groupOf(path: string): string | undefined {
  if (!path.endsWith('.gitignore')) return undefined;
  if (!path.includes('/')) return 'Languages & frameworks';
  if (/^Global\/[^/]+$/.test(path)) return 'Editors, tools & OS';
  if (path.startsWith('community/')) return 'Community';
  return undefined;
}

async function mapLimit<T, R>(items: T[], limit: number, fn: (item: T) => Promise<R>): Promise<R[]> {
  const out: R[] = new Array<R>(items.length);
  let next = 0;
  const workers = Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (next < items.length) {
      const i = next++;
      out[i] = await fn(items[i] as T);
    }
  });
  await Promise.all(workers);
  return out;
}

export async function refresh(): Promise<Dataset> {
  const commit = await getJson<{ sha: string }>(`${API}/commits/main`);
  const sha = commit.sha;
  const sha7 = sha.slice(0, 7);
  console.log(`  github/gitignore main is at ${sha}`);

  const tree = await getJson<{ tree: TreeEntry[]; truncated: boolean }>(`${API}/git/trees/${sha}?recursive=1`);
  if (tree.truncated) throw new Error('The git tree listing was truncated; refusing to build a partial dataset.');
  const files = tree.tree.filter((e) => e.type === 'blob' && groupOf(e.path) !== undefined).map((e) => e.path);
  console.log(`  downloading ${files.length} templates…`);

  const templates: Template[] = await mapLimit(files, 8, async (path) => ({
    name: (path.split('/').pop() ?? path).replace(/\.gitignore$/, ''),
    group: groupOf(path) ?? '',
    path,
    content: (await getText(`${RAW}/${sha}/${path.split('/').map(encodeURIComponent).join('/')}`)).replace(
      /\r\n?/g,
      '\n',
    ),
  }));
  const order = ['Languages & frameworks', 'Editors, tools & OS', 'Community'];
  templates.sort(
    (a, b) =>
      order.indexOf(a.group) - order.indexOf(b.group) ||
      a.name.localeCompare(b.name, 'en', { sensitivity: 'base' }) ||
      a.path.localeCompare(b.path),
  );

  const file = `gitignore-${sha7}.json`;
  writeFileSync(
    CONSTANT_FILE,
    `// Generated by \`node scripts/refresh-data.ts gitignore\`. Do not edit by hand.\nexport const DATA_FILE = 'data/${file}';\n`,
  );
  console.log(`  ~ src/tools/gitignore-generator/dataset.ts -> data/${file}`);

  return {
    name: 'gitignore',
    file,
    content: JSON.stringify({ commit: sha, templates }),
    source: 'github/gitignore',
    url: `https://github.com/${REPO}/tree/${sha}`,
    version: `commit ${sha7} (${sha})`,
    license: 'CC0-1.0',
    tool: 'gitignore-generator',
    notes: `${templates.length} templates: root \`*.gitignore\` (Languages & frameworks), \`Global/*.gitignore\` (Editors, tools & OS) and \`community/**/*.gitignore\` (Community).`,
  };
}
