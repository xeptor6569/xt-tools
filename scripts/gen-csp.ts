// Merges the CSP <meta> policies Astro wrote into every page and emits the
// same policy, plus frame-ancestors, as server header snippets. Browsers
// enforce every policy they receive, so the header must contain all the
// hashes the pages need. See PLAN.md section 9.3.
//
// Outputs (build/server/):
//   csp.txt          the policy, one line
//   csp.conf         nginx add_header directive (included by security-headers.conf)
//   base.conf        nginx redirect from / to the base path (empty when base is /)
//   apache.htaccess  header + rewrite snippet for Apache
//   Caddyfile        header snippet for Caddy
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { ROOT } from './lib/tools.ts';
import { decodeHtmlAttribute, walk } from './lib/fs.ts';

const DIST = join(ROOT, 'dist');
const OUT = join(ROOT, 'build', 'server');
const HEADER_ONLY = ["frame-ancestors 'self'"];

const META_RE = /<meta\s+http-equiv="content-security-policy"\s+content="([^"]*)"\s*\/?>/i;
const isHash = (source: string) => /^'sha(256|384|512)-/.test(source);

export function parsePolicy(policy: string): Map<string, string[]> {
  const map = new Map<string, string[]>();
  for (const part of policy.split(';')) {
    const [name, ...sources] = part.trim().split(/\s+/);
    if (name) map.set(name.toLowerCase(), sources);
  }
  return map;
}

export function serializePolicy(policy: Map<string, string[]>): string {
  return [...policy.entries()].map(([name, sources]) => [name, ...sources].join(' ')).join('; ');
}

export function generate(): { policy: string; problems: string[] } {
  const problems: string[] = [];
  const merged = new Map<string, string[]>();
  let reference: { file: string; base: Map<string, string[]> } | undefined;

  const pages = walk(DIST).filter((f) => f.endsWith('.html'));
  for (const file of pages) {
    const html = readFileSync(file, 'utf8');
    const name = relative(DIST, file);
    const match = META_RE.exec(html);
    if (!match?.[1]) {
      problems.push(`${name}: no CSP <meta> tag`);
      continue;
    }
    const before = html.slice(0, match.index);
    if (/<script\b|<style\b|<link\b[^>]*rel="?(stylesheet|modulepreload|preload)/i.test(before)) {
      problems.push(`${name}: a script, style or preload appears before the CSP <meta> tag`);
    }

    const policy = parsePolicy(decodeHtmlAttribute(match[1]));
    // Everything except hashes must be identical on every page.
    const base = new Map([...policy].map(([k, v]) => [k, v.filter((s) => !isHash(s))]));
    if (!reference) reference = { file: name, base };
    else if (serializePolicy(base) !== serializePolicy(reference.base)) {
      problems.push(`${name}: CSP differs from ${reference.file} (only hashes may vary between pages)`);
    }

    for (const [directive, sources] of policy) {
      const list = merged.get(directive) ?? [];
      for (const s of sources) if (!list.includes(s)) list.push(s);
      merged.set(directive, list);
    }
  }

  if (pages.length === 0) problems.push('dist/ contains no HTML pages; run astro build first');

  for (const extra of HEADER_ONLY) {
    const [name, ...sources] = extra.split(' ');
    if (name) merged.set(name, sources);
  }
  return { policy: serializePolicy(merged), problems };
}

export function writeSnippets(policy: string): void {
  const basePath = process.env.BASE_PATH ?? '/';
  mkdirSync(OUT, { recursive: true });
  writeFileSync(join(OUT, 'csp.txt'), `${policy}\n`);
  writeFileSync(
    join(OUT, 'csp.conf'),
    `# Generated by scripts/gen-csp.ts. Do not edit.\nadd_header Content-Security-Policy "${policy}" always;\n`,
  );
  writeFileSync(
    join(OUT, 'base.conf'),
    basePath === '/'
      ? '# Generated by scripts/gen-csp.ts. Base path is /, nothing to redirect.\n'
      : `# Generated by scripts/gen-csp.ts.\nlocation = / {\n    include /etc/nginx/snippets/security-headers.conf;\n    return 302 ${basePath};\n}\n`,
  );
  writeFileSync(
    join(OUT, 'apache.htaccess'),
    `# Generated by scripts/gen-csp.ts. Needs mod_headers.\n<IfModule mod_headers.c>\n  Header always set Content-Security-Policy "${policy}"\n  Header always set X-Content-Type-Options "nosniff"\n  Header always set X-Frame-Options "SAMEORIGIN"\n  Header always set Referrer-Policy "no-referrer"\n  Header always set Cross-Origin-Opener-Policy "same-origin"\n</IfModule>\nErrorDocument 404 ${basePath}404.html\nAddType application/javascript .mjs\nAddType application/manifest+json .webmanifest\nAddType application/wasm .wasm\n`,
  );
  writeFileSync(
    join(OUT, 'Caddyfile'),
    `# Generated by scripts/gen-csp.ts. Import inside your site block.\nheader {\n  Content-Security-Policy "${policy}"\n  X-Content-Type-Options "nosniff"\n  X-Frame-Options "SAMEORIGIN"\n  Referrer-Policy "no-referrer"\n  Cross-Origin-Opener-Policy "same-origin"\n  -Server\n}\n`,
  );
}

if (import.meta.main) {
  const { policy, problems } = generate();
  if (problems.length > 0) {
    console.error(`gen-csp: ${problems.length} problem(s):`);
    for (const p of problems) console.error(`  - ${p}`);
    process.exit(1);
  }
  writeSnippets(policy);
  console.log(`gen-csp: wrote build/server/ (${policy.length} characters).`);
}
